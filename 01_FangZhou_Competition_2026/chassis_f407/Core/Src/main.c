static void UpperTask(void *argument)
{
  ChassisRemoteStatus_t remote;
  uint8_t flags;

  (void)argument;

  for (;;)
  {
    ChassisRemote_GetStatus(&remote);
    flags = (remote.link_active != 0U) ? (remote.packet[4] & APP_UPPER_FLAG_MASK) : 0U;
    AppUpper_Task(flags);
    vTaskDelay(pdMS_TO_TICKS(5U));
  }
}

static void DisplayTask(void *argument)
{
  (void)argument;

  for (;;)
  {
    if ((HAL_GetTick() - s_led_tick) >= 500U)
    {
      HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);
      s_led_tick = HAL_GetTick();
    }
    if ((HAL_GetTick() - s_display_tick) >= 200U)
    {
      App_DisplayStatus();
    }
    vTaskDelay(pdMS_TO_TICKS(50U));
  }
}

static void App_DisplayStatus(void)
{
  VisionResult_t vision;
  char colors[22];

  if ((VisionComm_GetLatest(&vision) != 0U) &&
      (VisionComm_FormatQrColors(&vision, colors, sizeof(colors)) >= 1U))
  {
    AppOled_Clear();
    AppOled_PrintLine(2U, colors);
    AppOled_Update();
  }

  s_display_tick = HAL_GetTick();
}

